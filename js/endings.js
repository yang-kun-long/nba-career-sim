// 根据游戏状态计算结局
function calculateEnding(state) {
  // 按优先级排序：传奇 > 优质 > 悲剧 > 转型 > 普通
  const priority = ['legend','quality','tragedy','retire','normal'];
  const sorted = [...ENDINGS].sort((a,b) => {
    const ai = priority.indexOf(a.category);
    const bi = priority.indexOf(b.category);
    return ai - bi;
  });

  for (const ending of sorted) {
    try {
      if (ending.condition(state)) return ending;
    } catch(e) {}
  }

  // 默认结局
  return {
    id:'end_default',name:'篮球人生',category:'normal',rarity:'R',
    text:'你的篮球生涯结束了。虽然没有成为传奇，但你经历了属于自己的篮球人生。\n\n从12岁那个怀揣梦想的少年，到如今站在退役发布会上的老将，你走过了漫长的道路。你有过欢笑，有过泪水，有过成功，有过失败。但最重要的是，你从未放弃过对篮球的热爱。\n\n"我不知道我的职业生涯算不算成功，"你说，"但我知道，我尽力了。"\n\n退役后，你开始了新的生活。你可能会成为教练，可能会成为解说员，可能会成为普通的篮球爱好者。但无论你做什么，篮球永远是你生命的一部分。\n\n你的故事，就是千千万万篮球追梦者的缩影。你证明了，平凡也可以是伟大的。',
    desc:'默认结局'
  };
}

